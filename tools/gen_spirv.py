#!/usr/bin/env python3

import argparse
import os
import struct
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GPU = os.path.join(ROOT, "core", "src", "gpu")

SHADERS = [("kSpvConv3x3", "conv3x3.comp", None), ("kSpvEltwise", "eltwise.comp", None),
           ("kSpvResize", "resize.comp", None), ("kSpvConv4oc", "conv3x3_4oc.comp", "VVA_SPV_CONV4OC"),
           ("kSpvConv8px", "conv3x3_8px.comp", "VVA_SPV_CONV8PX")]

def spv_to_array(name, data):
    if len(data) % 4 != 0 or len(data) < 20:
        raise ValueError("%s: not a SPIR-V binary (%d bytes)" % (name, len(data)))
    words = struct.unpack("<%dI" % (len(data) // 4), data)
    if words[0] != 0x07230203:
        raise ValueError("%s: bad SPIR-V magic number" % name)
    lines = []
    for i in range(0, len(words), 8):
        lines.append("    " + ", ".join("0x%08x" % w for w in words[i:i + 8]) + ",")
    return "static const uint32_t %s[] = {\n%s\n};\n" % (name, "\n".join(lines))

def build_header(blobs):
    out = ["// Generated by tools/gen_spirv.py - do not edit or commit.", "#pragma once", "#include <cstdint>", ""]
    for name, macro, data in blobs:
        if data is None:
            out.append("static const uint32_t %s[] = {0x07230203, 0, 0, 0, 0};\n#define %s 0\n" % (name, macro))
        else:
            out.append(spv_to_array(name, data))
            if macro:
                out.append("#define %s 1\n" % macro)
    return "\n".join(out)

def compile_all(glslc, log=sys.stderr):
    blobs = []
    with tempfile.TemporaryDirectory() as tmp:
        for name, src, macro in SHADERS:
            spv = os.path.join(tmp, src + ".spv")
            cmd = [glslc, "-O", "--target-env=vulkan1.1", "-I", os.path.join(GPU, "kernels"), "-o", spv,
                   os.path.join(GPU, "shaders", src)]
            r = subprocess.run(cmd, capture_output=True, text=True)
            if r.returncode != 0:
                log.write(r.stdout + r.stderr)
                if macro is None:
                    raise RuntimeError("glslc failed on the required shader " + src)
                log.write("warning: leaving out the optional shader %s\n" % src)
                blobs.append((name, macro, None))
                continue
            with open(spv, "rb") as f:
                blobs.append((name, macro, f.read()))
    return blobs

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--glslc", required=True)
    ap.add_argument("--out", default=os.path.join(GPU, "spirv_data.h"))
    args = ap.parse_args()
    try:
        blobs = compile_all(args.glslc)
    except RuntimeError as exc:
        sys.exit(str(exc))
    with open(args.out, "w") as f:
        f.write(build_header(blobs))
    print("wrote", args.out, "(%d of %d optional shaders left out)" % (sum(1 for b in blobs if b[1] and b[2] is None), sum(1 for b in blobs if b[1])))

if __name__ == "__main__":
    main()
