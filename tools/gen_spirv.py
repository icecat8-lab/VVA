#!/usr/bin/env python3
"""Compiles the GPU kernels with glslc and writes core/src/gpu/spirv_data.h.

The header only exists in CI / release builds. Without it the library is built without GPU support and
everything runs on the CPU.

    python3 tools/gen_spirv.py --glslc /path/to/glslc [--out core/src/gpu/spirv_data.h]
"""

import argparse
import os
import struct
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GPU = os.path.join(ROOT, "core", "src", "gpu")
SHADERS = [("kSpvConv3x3", "conv3x3.comp"), ("kSpvEltwise", "eltwise.comp"), ("kSpvResize", "resize.comp")]


def spv_to_array(name, data):
    if len(data) % 4 != 0 or len(data) < 20:
        raise ValueError("%s: not a SPIR-V binary (%d bytes)" % (name, len(data)))
    words = struct.unpack("<%dI" % (len(data) // 4), data)
    if words[0] != 0x07230203:
        raise ValueError("%s: bad SPIR-V magic number" % name)
    lines = []
    for i in range(0, len(words), 8):
        lines.append("    " + ", ".join("0x%08x" % w for w in words[i:i + 8]) + ",")
    return "static const uint32_t %s[] = {\n%s\n};\n" % (name, "\n".join(lines))


def build_header(blobs):
    out = ["// Generated by tools/gen_spirv.py - do not edit or commit.", "#pragma once", "#include <cstdint>", ""]
    for name, data in blobs:
        out.append(spv_to_array(name, data))
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--glslc", required=True)
    ap.add_argument("--out", default=os.path.join(GPU, "spirv_data.h"))
    args = ap.parse_args()
    blobs = []
    with tempfile.TemporaryDirectory() as tmp:
        for name, src in SHADERS:
            spv = os.path.join(tmp, src + ".spv")
            cmd = [args.glslc, "-O", "--target-env=vulkan1.1", "-I", os.path.join(GPU, "kernels"), "-o", spv,
                   os.path.join(GPU, "shaders", src)]
            r = subprocess.run(cmd, capture_output=True, text=True)
            if r.returncode != 0:
                sys.stderr.write(r.stdout + r.stderr)
                sys.exit("glslc failed on " + src)
            with open(spv, "rb") as f:
                blobs.append((name, f.read()))
    with open(args.out, "w") as f:
        f.write(build_header(blobs))
    print("wrote", args.out)


if __name__ == "__main__":
    main()
